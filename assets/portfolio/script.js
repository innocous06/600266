      const tr = Math.floor(headR - step);
      if (tc >= 0 && tc < cols && tr >= 0 && tr < rows) {
        const charIdx = Math.min(tailChars.length - 1, Math.floor(tailP * tailChars.length));
        const tailAlpha = Math.max(0, (1 - tailP) * 0.85);
        cells.push({ col: tc, row: tr, char: tailChars[charIdx], alpha: tailAlpha });

        // Plume spread for medium size (slight lateral smoke puffs)
        if (step % 2 === 0 && step < 12) {
          const spreadC = tc + (step % 4 === 0 ? 1 : -1);
          if (spreadC >= 0 && spreadC < cols) {
            cells.push({ col: spreadC, row: tr, char: '·', alpha: tailAlpha * 0.45 });
          }
        }
      }

