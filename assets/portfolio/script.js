function scrambleString(original, resolveRatio, time, seedOffset) {
  if (resolveRatio >= 1) return original;
  const L = original.length;
  if (L === 0) return original;

  if (resolveRatio <= 0) {
    let out = '';
    for (let i = 0; i < L; i++) {
      const ch = original[i];
      if (ch === ' ' || ch === '\n' || ch === '\t') {
        out += ch;
      } else {
        const ci = Math.floor(Math.abs((time * 26 + seedOffset + i * 7)) % CHAOS_CHARS.length);
        out += CHAOS_CHARS[ci];
      }
    }
    return out;
  }

  let out = '';
  for (let i = 0; i < L; i++) {
    const ch = original[i];
    if (ch === ' ' || ch === '\n' || ch === '\t') {
      out += ch;
      continue;
    }
    const jitter = Math.sin(seedOffset + i * 137.5) * 0.5 + 0.5;
    const threshold = (i / L) * 0.65 + jitter * 0.35;

    if (resolveRatio >= threshold) {
      out += ch;
    } else {
      const ci = Math.floor(Math.abs((time * 28 + seedOffset + i * 11)) % CHAOS_CHARS.length);
      out += CHAOS_CHARS[ci];
    }
  }
  return out;
}

