// 5: Contact Idle Animation - Radar sweep + traveling telemetry packet pings
function idleContact(t, cols, rows) {
  const cells = [];
  const aspect = cellH / cellW;
  const cx = Math.floor(cols * 0.55);
  const cy = Math.floor(rows * 0.45);
  const maxR = Math.floor(rows * 0.38);

  // 1. 360-degree sweeping radar beam
  const sweepAngle = t * 1.5;
  for (let r = 4; r < maxR; r += 2) {
    const dc = Math.round(Math.cos(sweepAngle) * r * aspect);
    const dr = Math.round(Math.sin(sweepAngle) * r);
    const c = cx + dc;
    const row = cy + dr;
    if (c >= 0 && c < cols && row >= 0 && row < rows) {
      // Keep clear of bottom-left text area
      if (c < cols * 0.42 && row > rows * 0.55) continue;
      const alpha = 0.85 * (1 - r / maxR * 0.4);
      cells.push({ col: c, row, char: '*', alpha });
    }
  }

  // 2. Telemetry packets traveling along horizontal and vertical axes
  const pings = 4;
  for (let p = 0; p < pings; p++) {
    const dist = ((t * 18 + p * 25) % (cols * 0.45));
    // Traveling right on horizontal axis
    const cRight = Math.floor(cx + dist);
    if (cRight < cols - 2) {
      cells.push({ col: cRight, row: cy, char: '>', alpha: 0.75 });
    }
    // Traveling left on horizontal axis
    const cLeft = Math.floor(cx - dist);
    if (cLeft > cols * 0.40) {
      cells.push({ col: cLeft, row: cy, char: '<', alpha: 0.75 });
    }
    // Traveling up/down on vertical axis
    const distY = ((t * 10 + p * 15) % (rows * 0.42));
    const rUp = Math.floor(cy - distY);
    if (rUp > 2) {
      cells.push({ col: cx, row: rUp, char: '^', alpha: 0.70 });
    }
    const rDown = Math.floor(cy + distY);
    if (rDown < rows - 2) {
      cells.push({ col: cx, row: rDown, char: 'v', alpha: 0.70 });
    }
  }

  // 3. Ambient twinkling satellite nodes
  const starChars = ['+', '·', '*', 'x'];
  const nodes = [
    [cx - Math.floor(maxR * 0.7 * aspect), cy - Math.floor(maxR * 0.4)],
    [cx + Math.floor(maxR * 0.8 * aspect), cy - Math.floor(maxR * 0.3)],
    [cx + Math.floor(maxR * 0.6 * aspect), cy + Math.floor(maxR * 0.5)],
    [cx - Math.floor(maxR * 0.5 * aspect), cy + Math.floor(maxR * 0.4)]
  ];

  nodes.forEach(([nc, nr], ni) => {
    if (nc >= 0 && nc < cols && nr >= 0 && nr < rows) {
      const pulse = 0.35 + 0.45 * Math.sin(t * 3 + ni * 2);
      const ch = starChars[(Math.floor(t * 2 + ni)) % starChars.length];
      cells.push({ col: nc, row: nr, char: ch, alpha: pulse });
    }
  });

  return cells;
}

